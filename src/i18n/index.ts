export type TFunc = (key: string, vars?: Record<string, string | number>) => string

function interpolate(tpl: string, vars?: Record<string, string | number>): string {
  if (!vars) return tpl
  return tpl.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`))
}

const DICTS: Partial<Record<Language, Dict>> = { zh }
// en 在下方 Object.assign(en, {...}) 定义完成后挂载（DICTS.en = en）


export function makeT(lang: Language): TFunc {
  const dict = DICTS[lang] ?? zh
  return (key, vars) => interpolate(dict[key] ?? zh[key] ?? key, vars)
}

/** 组件内使用 */
export function useI18n(): TFunc {
  const lang = (useAppStore((s) => s.settings.language) ?? 'zh') as Language
  return useMemo(() => makeT(lang), [lang])
}

/** 非 React 环境：即时翻译单条 */
export function tNow(key: string, vars?: Record<string, string | number>): string {
  return makeT((useAppStore.getState().settings.language ?? 'zh') as Language)(key, vars)
}

/** 非 React 环境：连续多次调用时取翻译函数 */
export function tFn(): TFunc {
  return makeT((useAppStore.getState().settings.language ?? 'zh') as Language)
}

